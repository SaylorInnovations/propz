// Optional browser check: install Playwright and Chromium, start npm run dev, then run this file.
const { chromium } = await import(process.env.PROPZ_PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
const root=process.cwd();
const ext=root+'/extension';
const executablePath=process.env.PROPZ_CHROMIUM_PATH || chromium.executablePath();
const id=createHash('sha256').update(ext).digest('hex').slice(0,32).replace(/[0-9a-f]/g,c=>String.fromCharCode(97+parseInt(c,16)));
const context=await chromium.launchPersistentContext(await (await import('node:fs/promises')).mkdtemp((await import('node:os')).tmpdir()+'/propz-extension-'),{executablePath,headless:true,args:[`--disable-extensions-except=${ext}`,`--load-extension=${ext}`],viewport:{width:1280,height:800}});
const errors=[];
try {
const page=await context.newPage();page.on('pageerror', e=>errors.push(e.message));
await page.goto(`chrome-extension://${id}/popup.html`);
await page.locator('#base').fill('0x1111111111111111111111111111111111111111');
await page.locator('summary').click();
await page.locator('#name').fill('Demo Creator');
await page.locator('#message').fill('Thanks for supporting my work!');
await page.getByRole('button',{name:'Violet',exact:true}).click();
await page.getByRole('button',{name:'Save settings',exact:true}).click();
await page.waitForFunction(()=>document.getElementById('hint').textContent.includes('Settings saved'));
await page.reload();
assert.equal(await page.locator('#base').inputValue(),'0x1111111111111111111111111111111111111111');
assert.equal(await page.locator('#name').inputValue(),'Demo Creator');
const widget=await page.locator('#output').inputValue();
assert.match(widget,/data-accent="violet"/);
await page.locator('#copy').click();
await page.waitForFunction(()=>document.getElementById('hint').textContent.startsWith('Copied.'));
await mkdir(root+'/store-assets',{recursive:true});
await page.locator('summary').click();
await page.screenshot({path:root+'/store-assets/extension-builder.png'});
await page.locator('summary').click();
await page.locator('#sol').fill('invalid');assert.equal(await page.locator('#copy').isDisabled(),true);
await page.locator('#sol').fill('');
await page.locator('#format').selectOption('embed');
const embed=await page.locator('#output').inputValue();assert.match(embed,/<iframe/);
await page.locator('#format').selectOption('link');assert.match(await page.locator('#output').inputValue(),/\/jar\?/);
await page.locator('summary').click();await page.locator('#name').fill('\"><script>alert(1)</script>');
await page.locator('#format').selectOption('embed');
const unsafeEmbed=await page.locator('#output').inputValue();
const parsed=await page.evaluate(html=>{const d=new DOMParser().parseFromString(html,'text/html');return {count:d.querySelectorAll('iframe').length,scripts:d.querySelectorAll('script').length,title:d.querySelector('iframe').title}},unsafeEmbed);
assert.equal(parsed.count,1);assert.equal(parsed.scripts,0);assert.equal(parsed.title,'Send Propz to \"><script>alert(1)</script>');
console.log('Extension: loaded, settings persisted, clipboard copied, formats generated, invalid wallets blocked, HTML escaped.');
const browser=await chromium.launch({executablePath,headless:true});
try {
const visitor=await browser.newContext({viewport:{width:1280,height:800}});

const article=await visitor.newPage();article.on('pageerror',e=>errors.push(e.message));
await visitor.route('http://127.0.0.1:5173/__creator_demo',route=>route.fulfill({contentType:'text/html; charset=utf-8',body:`<!doctype html><html><head><title>Creator demo</title></head><body style="margin:0;background:#f6f4ef;color:#18293c;font-family:system-ui;padding:80px"><p>DEMO CREATOR / JOURNAL</p><h1 style="font-size:56px;max-width:650px">Independent work.<br>Community support.</h1><p style="font-size:22px;max-width:600px;line-height:1.7">A demonstration website showing a published Propz tip jar. Visitors can open the floating button without installing an extension.</p>${widget.replace("https://propz.saylorinnovations.com", "http://127.0.0.1:5173")}</body></html>`}));
await article.goto('http://127.0.0.1:5173/__creator_demo');
await article.getByRole('button',{name:'Send Propz',exact:true}).click();
const frame=article.frameLocator('iframe');
await frame.getByRole('heading',{name:'Demo Creator',exact:true}).waitFor();
await article.waitForTimeout(1500);
await article.screenshot({path:root+'/store-assets/website-widget.png'});
await article.getByRole('button',{name:'Close',exact:true}).click();
assert.equal(await article.getByRole('button',{name:'Send Propz',exact:true}).getAttribute('aria-expanded'),'false');
await article.setContent(embed.replace("https://propz.saylorinnovations.com", "http://127.0.0.1:5173"));await article.frameLocator('iframe').getByRole('heading',{name:'Demo Creator',exact:true}).waitFor();
console.log('Visitor without extension: generated widget opens correct card, closes, and iframe displays correct creator (hosted requests mapped to local build).');
const studio=await visitor.newPage();studio.on('pageerror',e=>errors.push(e.message));
await studio.goto('http://127.0.0.1:5173');
await studio.waitForLoadState('networkidle');
await studio.getByPlaceholder('0x... — accept USDC on Base').fill('0x1111111111111111111111111111111111111111');
await studio.getByPlaceholder('Your name or project').fill('Creator "quoted"');
await studio.getByRole('button',{name:'Embed',exact:true}).click();
assert.match(await studio.locator('.code-output code').innerText(),/&quot;quoted&quot;/);
await studio.getByPlaceholder('Accept SOL and USDC').fill('invalid');
assert.equal(await studio.getByRole('button',{name:'Copy',exact:true}).isDisabled(),true);
await studio.goto('http://127.0.0.1:5173/extension-privacy');
await studio.getByRole('heading',{name:'Generating and copying code'}).waitFor();
console.log('Studio and privacy: render correctly, safe embed output and mixed-wallet validation verified.');
assert.deepEqual(errors,[]);
console.log('No browser JavaScript errors.');
const promo=await visitor.newPage();
await promo.setViewportSize({width:440,height:280});
const {readFile}=await import('node:fs/promises');
await promo.setContent('<html><body style="margin:0">'+await readFile(root+'/store-assets/promo-tile.svg','utf8')+'</body></html>');
await promo.screenshot({path:root+'/store-assets/promo-tile.png'});
} catch(e) { console.error('CHECK FAILED:',e); console.error('PAGE ERRORS:',errors); throw e; } finally { for (const c of browser.contexts()) await c.unrouteAll({behavior:'ignoreErrors'}); await browser.close();}
} finally {await context.close();}
